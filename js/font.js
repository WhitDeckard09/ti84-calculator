  function compile(src, w, h) {
    var out = {};
    Object.keys(src).forEach(function (ch) {
      var rows = src[ch].split('/');
      if (rows.length !== h) throw new Error('font: ' + ch + ' has ' + rows.length + ' rows');
      out[ch] = rows.map(function (r) {
        if (r.length !== w) throw new Error('font: ' + ch + ' row width ' + r.length);
        var bits = 0;
        for (var i = 0; i < w; i++) if (r.charAt(i) === '#') bits |= (1 << (w - 1 - i));
        return bits;
      });
    });
    return out;
  }

